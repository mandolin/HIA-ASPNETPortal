<#
.SYNOPSIS
<lang>
  <zh-CN>手写页面新鲜度门禁（L0，静态）：不走生成流程的页面（首页 / 营销三页 / 八个分区页）必须与它们的"源"
  ——`_data/navigation.yml`——保持一致，且中英成对。</zh-CN>
  <en>Handwritten page freshness gate (L0, static): pages that do not go through the generation pipeline (the landing
  page / three marketing pages / eight section pages) must agree with their source — `_data/navigation.yml` — and must be
  paired across both languages.</en>
</lang>

.DESCRIPTION
<lang>
  <zh-CN>
    为什么需要这个门禁：`site/` 下有一批页面**不是 `Build-PortalSite.ps1` 生成的**——首页、营销三页
    （overview / features / compare）与八个分区页。它们**手工维护**，而"手工维护"在本项目里已经被证明
    会漂移：landing 上的统计数字曾从 31 手工改到 29，而真值是 27（那次之后才有了 landing 统计门禁）。
    分区页与之同型，但**当时没有人守**：它们承载的隐含契约是"**分区页的 title 必须等于
    `navigation.yml` 里的分区名**"——已上架页面的 `parent` 就是按这个字符串去匹配父页 title 的
    （Just the Docs 的 `nav_parenthood | where: "name", node.title`）。一旦两侧漂移，页面还在、
    链接不坏、`parent` 也仍然"有效"（构建 N1 只校验 parent 是否属于已知分区名），**但子页不会嵌套到
    分区下**——导航结构静默失效。这正是"本地绿、线上坏"的典型形态。

    三类断言（命中即失败，列出文件与原因）：
      S1 分区页标题 = 导航分区名：中文页 title ∈ `navigation.yml` 的 `title`；英文页 title ∈ `title_en`。
         双向核对：导航里的每个分区也必须有对应语言的分区页（否则该分区下永远不会展开）。
      S2 分区页 `nav_order` = 该分区在 `navigation.yml` 中的序号（1-based）——顺序漂移会让侧边栏
         与数据不一致，且不产生任何报错。
      S3 分区页 H1 存在、唯一、且等于 front matter 的 `title`（与模块文档页门禁的 M3a 同型：
         H1 丢了是静默的，标题会由 front matter 兜住，页面看起来正常）。
      S4 手写页中英成对：相对路径 R 与其 `en/R` 必须同时存在（首页与营销三页同样适用）。
      S5 分区页 permalink 命名空间：中文不以 `/en/` 开头，英文以 `/en/` 开头。

    **手写页如何界定（不硬编码）**：`published.yml` 声明的每条 `path` 会生成 `<path>/index.md`
    与 `<path>/en/index.md`；`site/` 下的其余 `index.md` 即为手写页。这样新增上架文档或新增分区
    都不需要改本门禁。

    刻意排除：首页与营销三页是 `layout: home` 的 **HTML 页**（正文是 `<section class="oc-hero">`，
    没有 markdown 一级标题、也不写 permalink），因此 S3 / S5 对它们不适用——若对它们要求 markdown
    H1，会立刻产生假失败。它们的 `parent` 与站内链接由构建的 N1/N2 校验。
  </zh-CN>
  <en>
    Why this gate exists: under `site/` there is a set of pages **not generated by `Build-PortalSite.ps1`** — the landing
    page, three marketing pages (overview / features / compare) and eight section pages. They are **maintained by hand**,
    and hand maintenance has already been shown to drift in this project: the landing statistics were manually changed
    from 31 to 29 while the truth was 27 (the landing-stats gate exists because of that). Section pages are the same
    shape, but **nobody was watching them**: their implicit contract is "**a section page's title must equal the section
    name in `navigation.yml`**" — published pages match their `parent` string against the parent page's title
    (Just the Docs: `nav_parenthood | where: "name", node.title`). If the two sides drift, the page still exists, no link
    breaks, and `parent` remains "valid" (build N1 only checks that a parent is a known section name), **yet children no
    longer nest under the section** — the navigation structure fails silently. That is the classic "green locally, broken
    online" shape.

    Three families of assertions (a hit fails the gate and lists file and reason):
      S1 section page title = navigation section name: a Chinese page's title ∈ `title` in `navigation.yml`; an English
         page's title ∈ `title_en`. Checked both ways: every navigation section must also have a section page in that
         language (otherwise that section never expands).
      S2 a section page's `nav_order` = its position in `navigation.yml` (1-based) — order drift desynchronises the
         sidebar from the data without producing any error.
      S3 a section page's H1 exists, is unique, and equals the front-matter `title` (same shape as criterion M3a of the
         module documentation gate: a lost H1 is silent, because the title is covered by front matter and the page looks
         normal).
      S4 handwritten pages are paired across languages: relative path R and its `en/R` must both exist (this applies to
         the landing page and the three marketing pages too).
      S5 section page permalink namespace: Chinese must not start with `/en/`, English must start with `/en/`.

    **How handwritten pages are identified (not hardcoded)**: every `path` declared in `published.yml` generates
    `<path>/index.md` and `<path>/en/index.md`; the remaining `index.md` files under `site/` are handwritten. Adding a
    published document or a new section therefore needs no change to this gate.

    Deliberate exclusions: the landing page and the three marketing pages are `layout: home` **HTML pages** (their body is
    `<section class="oc-hero">`, with no markdown level-1 heading and no permalink), so S3 and S5 do not apply to them —
    demanding a markdown H1 there would immediately produce false failures. Their `parent` and in-site links are validated
    by the build's N1/N2.
  </en>
</lang>

.Proof boundary（证明边界）
<lang>
  <zh-CN>
    只证明"**手写页与 `navigation.yml` 一致、中英成对、分区页 H1 正确**"。
    **不重复**已有门禁的职责：首页统计数字由 landing 统计门禁承载（A1/A2/A4/M0）；站内链接与
    `parent` 有效性由构建的 N1/N2 承载；镜像是否等于构建产物由镜像新鲜度门禁承载。
    **不证明**营销三页的文案是否准确、是否过时（那是人工复核，属公开面复核的范畴）；
    **不做语义判断**；**不检查**未上架的手写文件（`README.md` 之类）。
  </zh-CN>
  <en>
    Proves only that "**handwritten pages agree with `navigation.yml`, are paired across languages, and section pages have
    a correct H1**". It does **not duplicate** existing gates: landing statistics belong to the landing-stats gate
    (A1/A2/A4/M0); in-site links and `parent` validity belong to the build's N1/N2; whether the mirror equals the build
    output belongs to the mirror-freshness gate. It does **not** prove the marketing pages' copy is accurate or current
    (that is human review, part of the public-surface review); it makes **no semantic judgement**; it does **not** check
    unpublished handwritten files (`README.md` and similar).
  </en>
</lang>
#>
param(
    [string] $SiteRoot = ''
)

$ErrorActionPreference = 'Stop'
# `dev/scripts` → 上一级 `dev`，上上级仓库根
$repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if ([string]::IsNullOrWhiteSpace($SiteRoot)) { $SiteRoot = Join-Path $repoRoot 'site' }

function Get-FrontMatter {
    param([string] $Text)
    $m = [regex]::Match($Text, '(?s)\A---\r?\n(.*?)\r?\n---')
    if ($m.Success) { return $m.Groups[1].Value }
    return ''
}
function Get-FmValue {
    param([string] $Fm, [string] $Key)
    $m = [regex]::Match($Fm, '(?m)^' + $Key + ':\s*(.+?)\s*$')
    if ($m.Success) { return $m.Groups[1].Value.Trim() }
    return $null
}

$failures = New-Object 'System.Collections.Generic.List[string]'

# ---------- 1) 手写页集合：site/ 下的 index.md 减去生成页 ----------
# <lang>
#   <zh-CN>**手写页不硬编码**。`published.yml` 每条 `path` 会生成 `<path>/index.md` 与
#     `<path>/en/index.md`；`site/` 下其余的 `index.md` 就是手写页。新增上架文档或新增分区
#     都不需要改门禁——硬编码清单本身就会成为下一处漂移源。</zh-CN>
#   <en>**Handwritten pages are not hardcoded.** Every `path` in `published.yml` generates `<path>/index.md` and
#     `<path>/en/index.md`; the remaining `index.md` files under `site/` are handwritten. Adding a published document or
#     a new section needs no gate change — a hardcoded list would itself become the next source of drift.</en>
# </lang>
$generated = @{}
$manifest = [System.IO.File]::ReadAllText((Join-Path $SiteRoot '_data/published.yml'))
foreach ($m in [regex]::Matches($manifest, '(?m)^\s*path:\s*(.+?)\s*$')) {
    $p = $m.Groups[1].Value.Trim()
    if (-not $p) { continue }
    $generated[($p + '/index.md')] = $true
    $generated[($p + '/en/index.md')] = $true
}
$handwritten = @()
foreach ($f in (Get-ChildItem $SiteRoot -Recurse -File -Filter 'index.md')) {
    $rel = $f.FullName.Substring($SiteRoot.Length + 1).Replace('\', '/')
    if ($rel.StartsWith('_translations/')) { continue }
    if ($generated.ContainsKey($rel)) { continue }
    # 站点根 README 之类不是页面，跳过（只管 index.md 页面）
    $handwritten += $rel
}
$handwritten = @($handwritten | Sort-Object)
if ($handwritten.Count -eq 0) { Write-Host '[FAIL] 手写页集合为 0——无法核对（构建产物与上架清单不一致？）。'; exit 1 }
Write-Host ('[INFO] 手写页面新鲜度：手写页 ' + $handwritten.Count + ' 个（生成页 ' + $generated.Count + ' 个已排除）')

# ---------- 2) 导航数据 ----------
$navText = [System.IO.File]::ReadAllText((Join-Path $SiteRoot '_data/navigation.yml'))
$navEntries = New-Object 'System.Collections.Generic.List[object]'
$cur = $null
foreach ($line in ($navText -split "`r?`n")) {
    if ($line -match '^\s*-\s*title:\s*(.+?)\s*$') {
        if ($cur) { $navEntries.Add($cur) }
        $cur = @{ zh = $matches[1].Trim(); en = $null }
    }
    elseif ($line -match '^\s*title_en:\s*(.+?)\s*$' -and $cur) { $cur.en = $matches[1].Trim() }
}
if ($cur) { $navEntries.Add($cur) }
if ($navEntries.Count -eq 0) { Write-Host '[FAIL] 导航数据解析为 0 条分区——无法核对。'; exit 1 }
Write-Host ('[INFO] 导航分区 ' + $navEntries.Count + ' 条')

# ---------- 3) S4 双语成对 ----------
foreach ($rel in $handwritten) {
    $isEn = $rel.StartsWith('en/')
    $peer = if ($isEn) { $rel.Substring(3) } else { 'en/' + $rel }
    if (-not ($handwritten -contains $peer)) {
        $failures.Add(('S4 双语不成对：' + $rel + ' 缺少对应语言页面 ' + $peer))
    }
}

# ---------- 4) 分区页 S1 / S2 / S3 / S5 ----------
$sectionPages = @($handwritten | Where-Object { $_ -match '^(en/)?sections/[^/]+/index\.md$' })
Write-Host ('[INFO] 分区页 ' + $sectionPages.Count + ' 个')
foreach ($rel in $sectionPages) {
    $isEn = $rel.StartsWith('en/')
    $full = Join-Path $SiteRoot ($rel -replace '/', '\')
    $text = [System.IO.File]::ReadAllText($full)
    $fm = Get-FrontMatter $text
    $title = Get-FmValue $fm 'title'
    $order = Get-FmValue $fm 'nav_order'
    $perm = Get-FmValue $fm 'permalink'

    # S1 标题 = 导航分区名
    $names = @($navEntries | ForEach-Object { if ($isEn) { $_.en } else { $_.zh } })
    if (-not $title) { $failures.Add(('S1 分区页缺 title：' + $rel)) }
    elseif (-not ($names -contains $title)) {
        $failures.Add(('S1 分区页标题「' + $title + '」不在导航数据中：' + $rel + '（子页的 parent 将无法嵌套到它下面）'))
    }
    else {
        # S2 nav_order = 导航中的序号（1-based）
        $idx = 0
        for ($i = 0; $i -lt $navEntries.Count; $i++) {
            $n = if ($isEn) { $navEntries[$i].en } else { $navEntries[$i].zh }
            if ($n -eq $title) { $idx = $i + 1; break }
        }
        if (-not $order) { $failures.Add(('S2 分区页缺 nav_order：' + $rel)) }
        elseif ([int]$order -ne $idx) {
            $failures.Add(('S2 分区页 nav_order=' + $order + ' 与导航数据中的序号 ' + $idx + ' 不一致：' + $rel))
        }
    }

    # S3 H1 唯一且等于 title
    $h1s = @([regex]::Matches($text, '(?m)^#\s+(.+?)\s*$'))
    if ($h1s.Count -eq 0) { $failures.Add(('S3 分区页缺 H1：' + $rel)) }
    elseif ($h1s.Count -gt 1) { $failures.Add(('S3 分区页有多个 H1（' + $h1s.Count + ' 个）：' + $rel)) }
    elseif ($title -and $h1s[0].Groups[1].Value.Trim() -ne $title) {
        $failures.Add(('S3 分区页 H1「' + $h1s[0].Groups[1].Value.Trim() + '」与 title「' + $title + '」不一致：' + $rel))
    }

    # S5 permalink 命名空间
    if ($perm) {
        if ($isEn -and -not $perm.StartsWith('/en/')) { $failures.Add(('S5 英文分区页 permalink 未以 /en/ 开头：' + $rel + ' -> ' + $perm)) }
        if (-not $isEn -and $perm.StartsWith('/en/')) { $failures.Add(('S5 中文分区页 permalink 不应以 /en/ 开头：' + $rel + ' -> ' + $perm)) }
    }
}

# ---------- 5) 反向：每个导航分区都要有对应语言的分区页 ----------
foreach ($e in $navEntries) {
    foreach ($langPair in @(@{ name = $e.zh; lang = 'zh' }, @{ name = $e.en; lang = 'en' })) {
        $nm = $langPair.name
        if (-not $nm) { $failures.Add(('S1 导航分区缺少 ' + $langPair.lang + ' 标题：' + $e.zh)); continue }
        $found = $false
        foreach ($rel in $sectionPages) {
            $isEn = $rel.StartsWith('en/')
            if (($langPair.lang -eq 'en') -ne $isEn) { continue }
            $t = Get-FmValue (Get-FrontMatter ([System.IO.File]::ReadAllText((Join-Path $SiteRoot ($rel -replace '/', '\'))))) 'title'
            if ($t -eq $nm) { $found = $true; break }
        }
        if (-not $found) { $failures.Add(('S1 导航分区「' + $nm + '」没有对应语言的分区页（该分区下永远不会展开）')) }
    }
}

if ($failures.Count -eq 0) {
    Write-Host '[PASS] 手写页面新鲜度：分区页标题/顺序/H1 与导航数据一致、手写页中英成对、permalink 命名空间正确。'
    exit 0
}
foreach ($f in $failures) { Write-Host ('  [FAIL] ' + $f) }
Write-Host ('[FAIL] 手写页面新鲜度门禁失败：' + $failures.Count + ' 处。')
exit 1
